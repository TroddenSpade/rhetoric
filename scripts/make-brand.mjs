import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import opentype from 'opentype.js'
import sharp from 'sharp'

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..')
const fontPath = path.join(root, 'scripts', 'fonts', 'Parisienne-Regular.ttf')
const font = opentype.parse(fs.readFileSync(fontPath))

const INK = '#11151b'
const BONE = '#f2ede1'
const COBALT = '#8fa2ff'
const BRASS = '#b08a45'

const rPath = font.getPath('R', 0, 0, 100).toPathData(3)
const wordPath = font.getPath('Rhetoric', 0, 0, 100).toPathData(3)

// The icon R is scaled into the centre of a 512 square. The wordmark keeps the
// Parisienne drawing intact and adds a cobalt full stop after the final c.
const R_TRANSFORM = 'translate(60 370) scale(3.6)'
const ICON_DOT = { cx: 450, cy: 390, r: 6 }
const WORDMARK_VIEWBOX = '0 -82 344 96'
const WORDMARK_DOT = { cx: 335, cy: -4, r: 4.5 }

const rMark = `<g transform="${R_TRANSFORM}" color="${BONE}"><path d="${rPath}" fill="currentColor"/></g>
  <circle cx="${ICON_DOT.cx}" cy="${ICON_DOT.cy}" r="${ICON_DOT.r}" fill="${COBALT}"/>`

function iconSvg(rounded = true) {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512" width="512" height="512">
  <rect width="512" height="512"${rounded ? ' rx="112"' : ''} fill="${INK}"/>
  <circle cx="256" cy="256" r="196" fill="none" stroke="${BRASS}" stroke-width="3" opacity="0.38"/>
  ${rMark}
</svg>`
}

// The favicon crops the icon tightly and uses a slightly larger R so the letter
// remains legible at 16px.
const faviconSvg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512" width="512" height="512">
  <rect width="512" height="512" rx="112" fill="${INK}"/>
  <g transform="translate(40 386) scale(4.1)" color="${BONE}"><path d="${rPath}" fill="currentColor"/></g>
  <circle cx="478" cy="392" r="7" fill="${COBALT}"/>
</svg>`

const markSvg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="40 80 440 340" width="440" height="340">
  <g transform="${R_TRANSFORM}" color="${INK}"><path d="${rPath}" fill="currentColor"/></g>
  <circle cx="${ICON_DOT.cx}" cy="${ICON_DOT.cy}" r="${ICON_DOT.r}" fill="${COBALT}"/>
</svg>`

const wordmarkSvg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${WORDMARK_VIEWBOX}" width="344" height="96">
  <path d="${wordPath}" fill="${INK}"/>
  <circle cx="${WORDMARK_DOT.cx}" cy="${WORDMARK_DOT.cy}" r="${WORDMARK_DOT.r}" fill="${COBALT}"/>
</svg>`

fs.mkdirSync(path.join(root, 'public', 'brand'), { recursive: true })
fs.writeFileSync(path.join(root, 'public', 'favicon.svg'), faviconSvg)
fs.writeFileSync(path.join(root, 'public', 'brand', 'logo-mark.svg'), markSvg)
fs.writeFileSync(path.join(root, 'public', 'brand', 'logo-wordmark.svg'), wordmarkSvg)

fs.writeFileSync(
  path.join(root, 'src', 'components', 'logo-paths.js'),
  `// Generated by scripts/make-brand.mjs — do not edit by hand.\n` +
    `export const R_PATH =\n  '${rPath}'\n` +
    `export const R_TRANSFORM = '${R_TRANSFORM}'\n` +
    `export const ICON_DOT = ${JSON.stringify(ICON_DOT)}\n` +
    `export const WORDMARK_PATH =\n  '${wordPath}'\n` +
    `export const WORDMARK_VIEWBOX = '${WORDMARK_VIEWBOX}'\n` +
    `export const WORDMARK_DOT = ${JSON.stringify(WORDMARK_DOT)}\n`,
)

const icons = path.join(root, 'public', 'icons')
fs.mkdirSync(icons, { recursive: true })

async function render(svg, size, file) {
  await sharp(Buffer.from(svg)).resize(size, size).png().toFile(file)
}

await render(iconSvg(true), 192, path.join(icons, 'icon-192.png'))
await render(iconSvg(true), 512, path.join(icons, 'icon-512.png'))
await render(iconSvg(false), 512, path.join(icons, 'icon-maskable-512.png'))
await render(iconSvg(false), 180, path.join(icons, 'apple-touch-icon.png'))
await sharp(Buffer.from(markSvg)).png().toFile('/tmp/opencode/logo-mark.png')
await sharp(Buffer.from(wordmarkSvg)).png().toFile('/tmp/opencode/logo-wordmark.png')

console.log('brand generated')
